create schema if not exists ta_tkj;

create table if not exists ta_tkj.settings(
  key text primary key,
  value text not null
);

create table if not exists ta_tkj.students(
  id serial primary key,
  kelas text not null check (kelas in ('XII TKJ 1', 'XII TKJ 2')),
  no_absen int not null,
  name text not null,
  pin_hash text,
  project_id int,
  fails int not null default 0,
  locked_until timestamptz,
  unique (kelas, no_absen),
  unique (kelas, name)
);

create table if not exists ta_tkj.projects(
  id serial primary key,
  kelas text not null check (kelas in ('XII TKJ 1', 'XII TKJ 2')),
  lead_student_id int not null unique references ta_tkj.students(id) on delete cascade,
  title text not null,
  category text not null check (category in ('Web App', 'Android / Desktop', 'Jaringan & Otomasi', 'Bot / IoT / CLI')),
  delivery_mode text not null check (delivery_mode in ('WEB_LIVE', 'INSTALLABLE')),
  primary_url text not null,
  repo_url text not null default '',
  target_platform text not null default '',
  install_guide text not null default '',
  demo_account text not null default '',
  summary text not null default '',
  status text not null default 'MENUNGGU UJI' check (status in ('MENUNGGU UJI', 'SIAP PAKAI', 'REVISI WAJIB')),
  score_func int not null default 0 check (score_func between 0 and 100),
  score_ui int not null default 0 check (score_ui between 0 and 100),
  score_tech int not null default 0 check (score_tech between 0 and 100),
  score_total numeric(5,1) not null default 0,
  reviewer_note text not null default '',
  submitted_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  verified_at timestamptz
);

